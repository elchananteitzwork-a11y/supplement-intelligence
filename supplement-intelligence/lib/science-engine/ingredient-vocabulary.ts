//
// Shape mirrors lib/ingredient-registry/index.ts's `aliases` field: one
// canonical lowercase name plus real, known commercial/chemical/botanical
// name variants. A miss here degrades to today's exact behavior — honest
// absence, never a wrong match (R&D doc §4 Risks: "Vocabulary quality").
// Additions are one-line data changes, not a code change.

