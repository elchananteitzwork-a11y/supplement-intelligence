// no fuzzy matching, no fabrication).
//
// Deliberately does NOT duplicate TRACKED_INGREDIENTS (berberine, creatine,
// magnesium) — those stay the priority benchmark list, matched first and
// separately by matchTrackedIngredient() before this file is even
